import { compile } from 'json-schema-to-typescript';
import { dirname, join } from 'node:path';
import { loadSchemaFiles, SCHEMA_DIR } from '../../src/schemas.js';

const HEADER = '// Generated by `npm run gen` from schemas/. Do not edit by hand.\n/* eslint-disable */\n';

// One compile per top-level schema; shared $defs are emitted once (later duplicates are dropped by name).
export async function renderTypes(): Promise<string> {
  const files = loadSchemaFiles();
  const seen = new Set<string>();
  const chunks: string[] = [];
  for (const f of files.filter((x) => x.file !== 'common.json')) {
    const ts = await compile(structuredClone(f.schema), f.title, {
      bannerComment: '',
      additionalProperties: true,
      unreachableDefinitions: false,
      format: true,
      maxItems: -1,
      cwd: join(SCHEMA_DIR, dirname(f.file))
    });
    for (const decl of splitDeclarations(ts)) {
      if (!seen.has(decl.name)) {
        seen.add(decl.name);
        chunks.push(closeEnvelopeTypes(decl.text));
      }
    }
  }
  return HEADER + '\n' + chunks.join('\n\n') + '\n';
}

function splitDeclarations(ts: string): { name: string; text: string }[] {
  const out: { name: string; text: string }[] = [];
  const re = /(?:\/\*\*(?:(?!\*\/)[\s\S])*\*\/\s*)?export (?:interface|type) (\w+)[\s\S]*?(?=(?:\/\*\*(?:(?!\*\/)[\s\S])*\*\/\s*)?export (?:interface|type) |\s*$)/g;
  for (const m of ts.matchAll(re)) {
    out.push({ name: m[1]!, text: m[0].trim() });
  }
  return out;
}

// Envelope messages are closed with unevaluatedProperties, which the generator does not understand: drop its open index.
// x_ metrics next to optional standard metrics need an index type that admits undefined.
function closeEnvelopeTypes(text: string): string {
  text = text.replace(/\[k: string\]: number;/g, '[k: string]: number | undefined;');
  return /^(?:\/\*\*[\s\S]*?\*\/\s*)?export type \w+ = Envelope & \{/.test(text) ? text.replace(/\n {2}\[k: string\]: unknown;\n\};$/, '\n};') : text;
}
